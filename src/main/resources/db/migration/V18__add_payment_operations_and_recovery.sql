-- Refuse invalid balances; never infer historical refunds or replay resources.
ALTER TABLE member ADD COLUMN mileage_recovery_due INTEGER NOT NULL DEFAULT 0;
ALTER TABLE member ADD CONSTRAINT ck_member_mileage_nonnegative CHECK (mileage >= 0 AND mileage_recovery_due >= 0);
ALTER TABLE orders ADD COLUMN cancel_requested BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE payment ADD COLUMN refunded_at TIMESTAMPTZ;
CREATE TABLE payment_operation (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(order_id),
    operation_type VARCHAR(20) NOT NULL CHECK (operation_type IN ('CONFIRM','CANCEL_FULL')),
    status VARCHAR(24) NOT NULL CHECK (status IN ('READY','IN_FLIGHT','SUCCEEDED','REJECTED','UNKNOWN','MANUAL_REQUIRED')),
    payment_key VARCHAR(200), toss_order_id VARCHAR(64) NOT NULL,
    amount INTEGER NOT NULL CHECK (amount >= 0), reason VARCHAR(200),
    idempotency_key VARCHAR(300) NOT NULL UNIQUE,
    actor_type VARCHAR(20) NOT NULL, actor_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL, updated_at TIMESTAMPTZ NOT NULL,
    first_sent_at TIMESTAMPTZ, attempt_count INTEGER NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    next_attempt_at TIMESTAMPTZ, lease_token VARCHAR(36), lease_until TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0, last_error_code VARCHAR(80),
    pg_transaction_key VARCHAR(64), pg_approved_at TIMESTAMPTZ, pg_canceled_at TIMESTAMPTZ,
    CONSTRAINT uq_payment_operation_order_type UNIQUE (order_id, operation_type)
);
CREATE INDEX idx_payment_operation_due ON payment_operation(status, next_attempt_at, lease_until);
CREATE TABLE sales_rebuild_request (
    stat_date DATE PRIMARY KEY, requested_at TIMESTAMPTZ NOT NULL, last_error_code VARCHAR(80)
);
